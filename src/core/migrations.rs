use sqlx::PgPool;
use crate::core::error::AppResult;

pub async fn run_migrations(pool: &PgPool) -> AppResult<()> {
    let statements = [
        r#"CREATE TABLE IF NOT EXISTS users (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            username VARCHAR(50) UNIQUE NOT NULL,
            password_hash VARCHAR(255) NOT NULL,
            full_name VARCHAR(100) NOT NULL,
            role VARCHAR(20) NOT NULL DEFAULT 'user',
            status VARCHAR(20) NOT NULL DEFAULT 'approved',
            tier VARCHAR(20) NOT NULL DEFAULT 'trial',
            avatar_url TEXT,
            bio TEXT,
            equipment_json JSONB DEFAULT '{}'::jsonb,
            trial_brews_count INT NOT NULL DEFAULT 0,
            trial_locked_until TIMESTAMPTZ,
            subscription_plan_id VARCHAR(60) DEFAULT 'plan_trial',
            subscription_payment_method VARCHAR(50),
            subscription_activated_at TIMESTAMPTZ,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS tier VARCHAR(20) NOT NULL DEFAULT 'trial'",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS bio TEXT",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS equipment_json JSONB DEFAULT '{}'::jsonb",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS trial_brews_count INT NOT NULL DEFAULT 0",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS trial_locked_until TIMESTAMPTZ",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS subscription_plan_id VARCHAR(60) DEFAULT 'plan_trial'",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS subscription_payment_method VARCHAR(50)",
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS subscription_activated_at TIMESTAMPTZ",
        r#"CREATE TABLE IF NOT EXISTS auth_refresh_tokens (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            family_id UUID NOT NULL,
            token_hash VARCHAR(128) UNIQUE NOT NULL,
            device_id VARCHAR(100) NOT NULL DEFAULT 'mobile_default',
            device_name VARCHAR(120) NOT NULL DEFAULT 'Coffee Labs Mobile',
            ip_address VARCHAR(64),
            is_revoked BOOLEAN NOT NULL DEFAULT FALSE,
            expires_at TIMESTAMPTZ NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS feedbacks (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            user_id UUID REFERENCES users(id) ON DELETE SET NULL,
            username VARCHAR(100) NOT NULL,
            user_role VARCHAR(30) NOT NULL DEFAULT 'user',
            category VARCHAR(50) NOT NULL,
            feature_affected VARCHAR(100) NOT NULL,
            title VARCHAR(250) NOT NULL,
            description TEXT NOT NULL,
            rating INT DEFAULT 5,
            app_version VARCHAR(50) DEFAULT '1.0.0',
            device_info VARCHAR(100) DEFAULT 'Mobile',
            status VARCHAR(30) NOT NULL DEFAULT 'pending',
            admin_notes TEXT,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS app_version_configs (
            id VARCHAR(50) PRIMARY KEY DEFAULT 'default',
            platform VARCHAR(30) NOT NULL DEFAULT 'all',
            min_base_version VARCHAR(20) NOT NULL DEFAULT '1.0.0',
            latest_base_version VARCHAR(20) NOT NULL DEFAULT '1.0.0',
            min_build_number INT NOT NULL DEFAULT 1,
            latest_build_number INT NOT NULL DEFAULT 1,
            latest_patch_number INT NOT NULL DEFAULT 0,
            is_force_update BOOLEAN NOT NULL DEFAULT FALSE,
            is_patch_required BOOLEAN NOT NULL DEFAULT FALSE,
            release_notes TEXT NOT NULL DEFAULT 'Pembaruan stabilitas sistem, fitur feedback, dan optimasi performa Coffee Labs.',
            download_url TEXT,
            checksum_sha256 TEXT,
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS social_posts (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            user_id UUID REFERENCES users(id) ON DELETE SET NULL,
            author_name VARCHAR(100) NOT NULL,
            author_avatar TEXT,
            author_role VARCHAR(30) NOT NULL DEFAULT 'Barista',
            content TEXT NOT NULL,
            recipe_id INT,
            recipe_snapshot JSONB,
            likes_count INT NOT NULL DEFAULT 0,
            comments_count INT NOT NULL DEFAULT 0,
            copies_count INT NOT NULL DEFAULT 0,
            tags JSONB DEFAULT '[]'::jsonb,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS social_post_likes (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            post_id UUID NOT NULL REFERENCES social_posts(id) ON DELETE CASCADE,
            username VARCHAR(100) NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            CONSTRAINT unique_post_user_like UNIQUE (post_id, username)
        )"#,
        r#"CREATE TABLE IF NOT EXISTS social_comments (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            post_id UUID NOT NULL REFERENCES social_posts(id) ON DELETE CASCADE,
            parent_id UUID REFERENCES social_comments(id) ON DELETE CASCADE,
            user_id UUID REFERENCES users(id) ON DELETE SET NULL,
            author_name VARCHAR(100) NOT NULL,
            author_avatar TEXT,
            content TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        "ALTER TABLE social_comments ADD COLUMN IF NOT EXISTS parent_id UUID REFERENCES social_comments(id) ON DELETE CASCADE",
        r#"CREATE TABLE IF NOT EXISTS social_follows (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            follower_username VARCHAR(100) NOT NULL,
            following_username VARCHAR(100) NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            CONSTRAINT unique_follow_pair UNIQUE (follower_username, following_username)
        )"#,
        r#"CREATE TABLE IF NOT EXISTS user_recipes (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            user_id UUID REFERENCES users(id) ON DELETE CASCADE,
            username VARCHAR(100) NOT NULL DEFAULT 'guest',
            recipe_local_id BIGINT NOT NULL,
            title VARCHAR(200) NOT NULL,
            method VARCHAR(80) NOT NULL DEFAULT 'Hario V60 02',
            category VARCHAR(50) NOT NULL DEFAULT 'V60',
            is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
            recipe_data JSONB NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS brew_logs (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            user_id UUID REFERENCES users(id) ON DELETE CASCADE,
            username VARCHAR(100) NOT NULL DEFAULT 'guest',
            log_type VARCHAR(30) NOT NULL DEFAULT 'history',
            entry_local_id BIGINT,
            method VARCHAR(80) NOT NULL DEFAULT 'V60',
            bean_name VARCHAR(150),
            rating DOUBLE PRECISION DEFAULT 4.5,
            payload JSONB NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS curated_beans (
            id VARCHAR(100) PRIMARY KEY,
            name VARCHAR(180) NOT NULL,
            roastery_name VARCHAR(120) NOT NULL,
            roastery_city VARCHAR(80) NOT NULL,
            origin VARCHAR(120) NOT NULL,
            variety VARCHAR(100) NOT NULL,
            process VARCHAR(100) NOT NULL,
            roast_level VARCHAR(50) NOT NULL,
            tasting_notes TEXT NOT NULL,
            price_100g INT NOT NULL DEFAULT 75000,
            price_200g INT NOT NULL DEFAULT 145000,
            rating DOUBLE PRECISION NOT NULL DEFAULT 4.9,
            metadata JSONB DEFAULT '{}'::jsonb,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS marketplace_orders (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            order_code VARCHAR(50) UNIQUE NOT NULL,
            user_id UUID REFERENCES users(id) ON DELETE SET NULL,
            username VARCHAR(100) NOT NULL,
            recipient_name VARCHAR(120) NOT NULL,
            phone_number VARCHAR(40) NOT NULL,
            shipping_address TEXT NOT NULL,
            courier_name VARCHAR(80) NOT NULL,
            payment_method VARCHAR(60) NOT NULL,
            voucher_code VARCHAR(50),
            subtotal INT NOT NULL,
            shipping_fee INT NOT NULL,
            discount INT NOT NULL DEFAULT 0,
            total INT NOT NULL,
            status VARCHAR(50) NOT NULL DEFAULT 'Confirmed & Roasting',
            items_json JSONB NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        "CREATE INDEX IF NOT EXISTS idx_users_username ON users(username)",
        "CREATE INDEX IF NOT EXISTS idx_users_status ON users(status)",
        "CREATE INDEX IF NOT EXISTS idx_refresh_family ON auth_refresh_tokens(family_id)",
        "CREATE INDEX IF NOT EXISTS idx_refresh_user ON auth_refresh_tokens(user_id)",
        "CREATE INDEX IF NOT EXISTS idx_feedbacks_created_at ON feedbacks(created_at DESC)",
        "CREATE INDEX IF NOT EXISTS idx_feedbacks_status ON feedbacks(status)",
        "CREATE INDEX IF NOT EXISTS idx_social_posts_cursor ON social_posts(created_at DESC, id DESC)",
        "CREATE INDEX IF NOT EXISTS idx_social_post_likes_post ON social_post_likes(post_id)",
        "CREATE INDEX IF NOT EXISTS idx_social_comments_post ON social_comments(post_id, created_at ASC)",
        "CREATE INDEX IF NOT EXISTS idx_brew_logs_user ON brew_logs(username, created_at DESC)",
        "CREATE INDEX IF NOT EXISTS idx_user_recipes_user ON user_recipes(username, updated_at DESC)",
        "CREATE INDEX IF NOT EXISTS idx_orders_user ON marketplace_orders(username, created_at DESC)",
        r#"CREATE TABLE IF NOT EXISTS business_store_configs (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            owner_user_id UUID NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
            store_name VARCHAR(120) NOT NULL DEFAULT 'Coffee Labs Bar',
            cashier_pin_hash TEXT NOT NULL,
            aod_grid_columns INT NOT NULL DEFAULT 3,
            aod_grid_rows INT NOT NULL DEFAULT 2,
            aod_card_border_color VARCHAR(30) NOT NULL DEFAULT '#262626',
            aod_accent_color VARCHAR(30) NOT NULL DEFAULT '#D4AF37',
            aod_idle_brightness REAL NOT NULL DEFAULT 0.35,
            aod_active_brightness REAL NOT NULL DEFAULT 0.90,
            pixel_shift_enabled BOOLEAN NOT NULL DEFAULT true,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS business_menu_items (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            store_id UUID NOT NULL REFERENCES business_store_configs(id) ON DELETE CASCADE,
            name VARCHAR(80) NOT NULL,
            description VARCHAR(240) NOT NULL DEFAULT '',
            category VARCHAR(50) NOT NULL DEFAULT 'Signature Coffee',
            price_cents BIGINT NOT NULL,
            currency VARCHAR(10) NOT NULL DEFAULT 'IDR',
            asset_url TEXT NOT NULL,
            asset_format VARCHAR(10) NOT NULL,
            has_verified_transparency BOOLEAN NOT NULL DEFAULT true,
            display_order INT NOT NULL DEFAULT 0,
            is_available BOOLEAN NOT NULL DEFAULT true,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS pos_orders (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            store_id UUID NOT NULL REFERENCES business_store_configs(id) ON DELETE CASCADE,
            order_number VARCHAR(40) NOT NULL,
            cashier_user_id UUID REFERENCES users(id) ON DELETE SET NULL,
            customer_name VARCHAR(100) DEFAULT 'Customer Bar',
            subtotal_cents BIGINT NOT NULL,
            tax_cents BIGINT NOT NULL DEFAULT 0,
            total_cents BIGINT NOT NULL,
            payment_method VARCHAR(50) NOT NULL DEFAULT 'Cash',
            status VARCHAR(30) NOT NULL DEFAULT 'completed',
            notes TEXT,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )"#,
        r#"CREATE TABLE IF NOT EXISTS pos_order_items (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            order_id UUID NOT NULL REFERENCES pos_orders(id) ON DELETE CASCADE,
            menu_item_id UUID REFERENCES business_menu_items(id) ON DELETE SET NULL,
            item_name VARCHAR(80) NOT NULL,
            quantity INT NOT NULL DEFAULT 1,
            unit_price_cents BIGINT NOT NULL,
            subtotal_cents BIGINT NOT NULL,
            modifiers_json JSONB DEFAULT '{}'::jsonb
        )"#,
        "CREATE INDEX IF NOT EXISTS idx_store_owner ON business_store_configs(owner_user_id)",
        "CREATE INDEX IF NOT EXISTS idx_menu_store ON business_menu_items(store_id, display_order ASC)",
        "CREATE INDEX IF NOT EXISTS idx_pos_orders_store ON pos_orders(store_id, created_at DESC)",
        "CREATE INDEX IF NOT EXISTS idx_pos_order_items_order ON pos_order_items(order_id)",
        "ALTER TABLE business_menu_items ADD COLUMN IF NOT EXISTS show_in_aod BOOLEAN NOT NULL DEFAULT true",
        "ALTER TABLE business_menu_items ADD COLUMN IF NOT EXISTS show_in_pos BOOLEAN NOT NULL DEFAULT true",
    ];

    for sql in statements {
        sqlx::query(sql).execute(pool).await?;
    }
    Ok(())
}
